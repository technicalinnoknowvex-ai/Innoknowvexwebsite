function normalizeProgramToolSlug(programSlug) {
  return String(programSlug)
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function getCanonicalProgramToolSlug(programSlug) {
  const normalizedSlug = normalizeProgramToolSlug(programSlug);
  const aliasedSlug = programToolSlugAliases[normalizedSlug] || normalizedSlug;
  if (programTools[aliasedSlug]) return aliasedSlug;

  const matchingAlias = Object.keys(programToolSlugAliases)
    .sort((left, right) => right.length - left.length)
    .find((alias) => normalizedSlug.includes(alias));
  if (matchingAlias) return programToolSlugAliases[matchingAlias];

  const matchingSlug = Object.keys(programTools)
    .sort((left, right) => right.length - left.length)
    .find((slug) => normalizedSlug.includes(slug));
  return matchingSlug;
}

export const getProgramTools = (programSlug) => {
  if (!programSlug) {
    return [];
  }

  const canonicalSlug = getCanonicalProgramToolSlug(programSlug);
  return canonicalSlug ? programTools[canonicalSlug] : [];
};

export const getProgramToolIcons = (programSlug) => {
  const tools = getProgramTools(programSlug);
  return tools.map((tool) => ({
    name: tool,
    icon: toolIcons[tool] || Sparkles,
  }));
};

export const getProgramToolLabel = (programSlug) => {
  if (!programSlug) {
    return "Program";
  }

  const canonicalSlug = getCanonicalProgramToolSlug(programSlug);
  return (canonicalSlug && programToolLabels[canonicalSlug]) || "Program";
};

